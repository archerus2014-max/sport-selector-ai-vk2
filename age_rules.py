def is_age_allowed(sport_id, age):
    """
    Проверяет, можно ли включать вид спорта
    в рекомендации для данного возраста.
    """

    rule = AGE_RULES.get(sport_id)

    if not rule:
        return False

    return (
        rule["min_age"] <= age <= rule["max_age"]
    )


def get_age_rule(sport_id):
    """
    Возвращает возрастное правило конкретного вида спорта.
    """

    return AGE_RULES.get(sport_id)


def get_min_age(sport_id):
    """
    Возвращает минимальный возраст.
    """

    rule = AGE_RULES.get(sport_id)

    if not rule:
        return None

    return rule["min_age"]


def get_max_age(sport_id):
    """
    Возвращает максимальный возраст.
    """

    rule = AGE_RULES.get(sport_id)

    if not rule:
        return None

    return rule["max_age"]