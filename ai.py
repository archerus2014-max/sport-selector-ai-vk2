            "🏅 ИТОГОВАЯ РЕКОМЕНДАЦИЯ\n\n"
            f"По результатам теста первое место занимает "
            f"{first['name']} — {first['score']}%.\n\n"
            "🎯 Рекомендуем начать с пробного занятия "
            "именно по этому виду спорта.\n\n"
            "Важно посмотреть, насколько ребёнку "
            "понравятся занятие, тренер и атмосфера "
