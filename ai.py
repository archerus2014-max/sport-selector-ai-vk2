def build_recommendations_text(
    recommendations
):

    lines = []

    for index, sport in enumerate(
        recommendations[:3],
        start=1
    ):

        age_rule = sport.get(
            "age_rule",
            {}
        )

        min_age = age_rule.get(
            "min_age",
            "не указан"
        )

        max_age = age_rule.get(
            "max_age",
            "не указан"
        )

        lines.append(
            f"""
{index}. {sport['name']}
Процент соответствия: {sport['score']}%
Возрастной диапазон: {min_age}-{max_age} лет
"""
        )

    return "\n".join(
        lines
    )


# ============================================================
# ПОДГОТОВКА ИСКЛЮЧЁННЫХ ВИДОВ СПОРТА
# ============================================================

def build_excluded_text(
    excluded
):

    if not excluded:

        return (
            "Возрастных ограничений, "
            "исключивших виды спорта, нет."
        )

    lines = []

    for sport in excluded:

        lines.append(
            f"- {sport['name']}: "
            f"минимальный возраст "
            f"{sport['min_age']} лет. "
            f"{sport['reason']}"
        )

    return "\n".join(
        lines
    )


