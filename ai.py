def get_gigachat_text(response):
    """
    Универсальное получение текста ответа GigaChat.

    В разных версиях библиотеки структура ответа
    может отличаться.

    Поэтому не используем напрямую:
        response.choices[0].message.content

    а проверяем несколько возможных вариантов.
    """

    # --------------------------------------------------------
    # Вариант 1
    # --------------------------------------------------------

    if hasattr(response, "content"):

        content = response.content

        if content:
            return str(content).strip()

    # --------------------------------------------------------
    # Вариант 2
    # --------------------------------------------------------

    if hasattr(response, "message"):

        message = response.message

        if hasattr(message, "content"):

            content = message.content

            if content:
                return str(content).strip()

    # --------------------------------------------------------
    # Вариант 3
    # --------------------------------------------------------

    if hasattr(response, "choices"):

        choices = response.choices

        if choices:

            first_choice = choices[0]

            if hasattr(
                first_choice,
                "message"
            ):

                message = first_choice.message

                if hasattr(
                    message,
                    "content"
                ):

                    content = message.content

                    if content:
                        return str(
                            content
                        ).strip()

    # --------------------------------------------------------
    # Если структура неизвестна
    # --------------------------------------------------------

    return str(response)


