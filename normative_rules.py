def get_age_rule(sport_id):
    """
    Возвращает возрастное правило для вида спорта.
    """

    return AGE_RULES.get(
        sport_id,
        {
            "min_age": 18,
            "max_age": 18,
            "description": "Возрастные данные отсутствуют.",
            "priority_for_young_children": False,
        }
    )


def is_age_allowed(sport_id, age):
    """
    Проверяет, подходит ли возраст ребёнка
    для предварительной рекомендации.
    """

    rule = get_age_rule(sport_id)

    return (
        rule["min_age"]
        <= age
        <= rule["max_age"]
    )


def get_age_reason(sport_id, age):
    """
    Возвращает понятное пользователю объяснение.
    """

    rule = get_age_rule(sport_id)

    min_age = rule["min_age"]
    max_age = rule["max_age"]

    if age < min_age:
        return (
            f"Ребёнку {age} лет. "
            f"Для этого направления установлен минимальный возраст "
            f"предварительного допуска — {min_age} лет."
        )

    if age > max_age:
        return (
            f"Возраст ребёнка ({age} лет) превышает "
            f"расчётный возрастной диапазон до {max_age} лет."
        )

    return "Возраст соответствует установленному диапазону."