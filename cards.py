# =====================================================
# ПРОГРЕСС-БАР
# =====================================================

def progress_bar(percent):

    size = 10

    filled = int(
        percent / 10
    )

    return (
        "█" * filled +
        "░" * (size-filled)
    )



# =====================================================
# ПОЛ РЕБЁНКА
# =====================================================

def gender_icon(gender):

    if "маль" in gender.lower():

        return "👦"


    if "дев" in gender.lower():

        return "👧"


    return "👤"



# =====================================================
# СПОРТИВНЫЙ ТИП
# =====================================================

def sport_profile(answers):


    strength = answers.get(
        "strength",
        3
    )

    speed = answers.get(
        "speed",
        3
    )

    coordination = answers.get(
        "coordination",
        3
    )

    flexibility = answers.get(
        "flexibility",
        3
    )



    if coordination >=4 and flexibility >=4:

        return (
            "🤸 Координационно-гибкий тип\n\n"
            "Сильные стороны:\n"
            "✔ контроль тела\n"
            "✔ ловкость\n"
            "✔ чувство равновесия"
        )


    if speed >=4:

        return (
            "⚡ Скоростной тип\n\n"
            "Сильные стороны:\n"
            "✔ реакция\n"
            "✔ быстрота\n"
            "✔ динамика"
        )


    if strength >=4:

        return (
            "💪 Силовой тип\n\n"
            "Сильные стороны:\n"
            "✔ мощность\n"
            "✔ волевые качества\n"
            "✔ физическая сила"
        )


    return (
        "🎯 Универсальный тип\n\n"
        "Сильные стороны:\n"
        "✔ обучаемость\n"
        "✔ адаптация\n"
        "✔ разносторонность"
    )



