def age_recommendation(age):


    if age <= 6:

        return """
Возраст 5–6 лет:

Главная задача —
развитие общей физической базы.

Фокус:

🤸 координация
⚖ равновесие
🤸 гибкость
🎯 интерес к движению

Не рекомендуется ранняя узкая специализация.
"""


    elif age <=10:

        return """
Возраст 7–10 лет:

Период активного формирования
двигательных навыков.

Важно развивать:

⚡ скорость
🤸 координацию
💪 общую силу
"""


    else:

        return """
Возраст 11+:

Можно переходить
к более выраженной спортивной специализации.

Важно учитывать:
интерес ребёнка,
мотивацию и регулярность занятий.
"""



# =====================================================
# ОСНОВНАЯ КАРТОЧКА
# =====================================================

def result_card(
        data,
        results
):


    age = data.get(
        "age",
        "-"
    )


    gender = data.get(
        "gender",
        ""
    )


    answers = data.get(
        "answers",
        {}
    )



    text = """

━━━━━━━━━━━━━━
🏆 AI-ПОДБОР СПОРТА
━━━━━━━━━━━━━━

"""


    text += (

        f"{gender_icon(gender)} "
        f"Возраст: {age} лет\n\n"

    )


    text += (

        "📊 СПОРТИВНЫЙ ПРОФИЛ\n"
        "━━━━━━━━━━━━━━\n\n"

    )


    text += sport_profile(
        answers
    )


    text += (

        "\n\n━━━━━━━━━━━━━━\n"
        "🥇 ТОП-3 НАПРАВЛЕНИЯ\n"
        "━━━━━━━━━━━━━━\n"

    )



    medals = [

        "🥇",
        "🥈",
        "🥉"

    ]



    for i,item in enumerate(results[:3]):


        sport = item["sport"]

        percent = item["percent"]


        text += (

            f"\n{medals[i]} {sport}\n"
            f"Соответствие: {percent}%\n"
            f"{progress_bar(percent)}\n"

        )


        text += sport_card(
            sport,
            percent
        )



    text += (

        "\n━━━━━━━━━━━━━━\n"
        "📌 ВОЗРАСТНАЯ РЕКОМЕНДАЦИЯ\n"
        "━━━━━━━━━━━━━━\n"

    )


    text += age_recommendation(
        int(age)
    )



    text += (

        "\n━━━━━━━━━━━━━━\n"
        "Важно:\n"
        "Результат является рекомендацией.\n"
        "Окончательный выбор зависит\n"
        "от интереса ребёнка и желания заниматься."
    )


    return text